pub fn glyph(ch: u8) *const [16]u16 {
    if (ch < FIRST or ch > LAST) return &glyphs[0];
    return &glyphs[ch - FIRST];
}

pub fn advance(ch: u8) u32 {
    if (ch < FIRST or ch > LAST) return advances[0];
    return advances[ch - FIRST];
}

pub fn textWidth(text: []const u8) u32 {
    var w: u32 = 0;
    for (text) |ch| w += advance(ch);
    return w;
}

fn putPx(fb: []u8, stride: u32, width: u32, x: u32, y: u32, color: u32) void {
    if (x >= width) return;
    const o: usize = @as(usize, y) * @as(usize, stride) + @as(usize, x) * 4;
    if (o + 3 >= fb.len) return;
    fb[o + 0] = @truncate(color >> 16);
    fb[o + 1] = @truncate(color >> 8);
    fb[o + 2] = @truncate(color);
    fb[o + 3] = @truncate(color >> 24);
}

/// Crisp glyph blit (1-bit ink). Fringe AA looked like a glow/halo on dark UI.
pub fn blitGlyph(fb: []u8, stride: u32, width: u32, x0: u32, y0: u32, ch: u8, color: u32) void {
    const g = glyph(ch);
    var row: u32 = 0;
    while (row < GLYPH_H) : (row += 1) {
        const bits = g.*[row];
        var col: u32 = 0;
        while (col < GLYPH_W) : (col += 1) {
            if ((bits & (@as(u16, 1) << @intCast(col))) != 0) {
                putPx(fb, stride, width, x0 + col, y0 + row, color);
            }
        }
    }
}

pub fn blitText(fb: []u8, stride: u32, width: u32, x0: u32, y0: u32, text: []const u8, color: u32) void {
    var x: u32 = x0;
    for (text) |ch| {
        blitGlyph(fb, stride, width, x, y0, ch, color);
        x += advance(ch);
    }
}
